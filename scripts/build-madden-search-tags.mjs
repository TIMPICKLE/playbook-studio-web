import { writeFile } from 'node:fs/promises';
import catalog from '../web/data/huddle-catalog.json' with { type: 'json' };
import { getEditableEntry } from '../web/madden-model.js';
import { traceConceptTags } from '../web/madden-concepts.js';

const entries = {};
const names = {};
for (const play of catalog.plays) {
  const trace = getEditableEntry(play.id);
  if (trace) entries[play.id] = traceConceptTags(trace);
  const title = play.name.toUpperCase();
  const nameTags = [
      [/\bFLOOD\b/, 'flood'], [/\bSMASH\b/, 'smash'], [/\bCURLS?(?=\b|[XYZ]\b)/, 'curl'],
      [/\bVERTICALS?\b/, 'vertical'], [/\bFOUR\s+VERTICALS?\b|\b4\s+VERTS?\b/, 'four verts'],
      [/\bMESH\b/, 'mesh'],
  ].filter(([pattern]) => pattern.test(title)).map(([, tag]) => tag);
  if (nameTags.length) names[play.id] = nameTags;
}
await writeFile(new URL('../web/data/madden-search-tags.js', import.meta.url),
  '// Generated by scripts/build-madden-search-tags.mjs from editable route geometry and catalog names.\nexport const MADDEN_CONCEPT_TAGS = ' + JSON.stringify(entries, null, 2) + ';\n' +
  'export const MADDEN_NAME_TAGS = ' + JSON.stringify(names, null, 2) + ';\n');
