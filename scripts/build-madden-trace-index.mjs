import { readFile, writeFile } from 'node:fs/promises';
import { TEAM_TRACE_ALIASES } from '../web/data/madden-team-trace-aliases.js';
import { SEED_TRACES } from '../web/data/madden-editable-seed.js';
import { BATCH_TRACES } from '../web/data/madden-editable-batch.js';
import { EXPANDED_TRACES } from '../web/data/madden-editable-80.js';
import { REVIEWED_OCT28_TRACES } from '../web/data/madden-editable-oct28.js';
import { CONTINUED_TRACES } from '../web/data/madden-editable-continued.js';
import { FINAL_TRACES } from '../web/data/madden-editable-final.js';

// Keep the same override order as madden-editable.js. The browser needs a small
// existence index and search evidence, not all intermediate route coordinates.
const batches = {seed:SEED_TRACES,batch:BATCH_TRACES,expanded:EXPANDED_TRACES,oct28:REVIEWED_OCT28_TRACES,continued:CONTINUED_TRACES,final:FINAL_TRACES};
const shards = {}, evidence = {};
for (const [shard, traces] of Object.entries(batches)) for (const [id, trace] of Object.entries(traces)) {
  shards[id] = shard;
  const endpoints = trace.routes.filter(route => route.kind === 'route' && !route.optional)
    .map(route => `${route.owner} ${route.points[0].join(',')}→${route.points.at(-1).join(',')}`);
  evidence[id] = `Editable trace: primary route start→finish (source px; right +x, downfield −y, LOS y=${trace.coordinateSystem.lineOfScrimmageY}): ${endpoints.join('; ')}.`;
}
for (const [alias, id] of Object.entries(TEAM_TRACE_ALIASES)) {
  if (!Object.hasOwn(shards, id) || Object.hasOwn(shards, alias)) throw new Error(`Invalid trace alias: ${alias}`);
}
const sorted = value => Object.fromEntries(Object.entries(value).sort(([a],[b]) => a.localeCompare(b)));
for (const [name, exported, value] of [
  ['madden-trace-index.js','TRACE_SHARDS',shards],
  ['madden-trace-evidence.js','TRACE_EVIDENCE',evidence],
]) {
  const target = new URL(`../web/data/${name}`, import.meta.url);
  const content = `// Generated by scripts/build-madden-trace-index.mjs; do not edit by hand.\nexport const ${exported} = ${JSON.stringify(sorted(value), null, 2)};\n`;
  if (process.argv.includes('--check')) {
    if (await readFile(target,'utf8') !== content) throw new Error(`${name} is stale; regenerate the Madden trace index.`);
  } else await writeFile(target, content);
}
